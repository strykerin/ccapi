import json
import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
MBX = '{https://developers.binance.com/docs/binance-spot-api-docs}'
SBE = '{http://fixprotocol.io/2016/sbe}'
# Production FIX endpoints still require version 1 requests (verified 2026-11-05).
FIX_REQUEST_VERSION = 1
SIZES = {'char':1,'int8':1,'uint8':1,'int16':2,'uint16':2,'int32':4,'uint32':4,'int64':8,'uint64':8}

def generate(filename, ns, selected=None):
    root=ET.parse(ROOT/'spec'/filename).getroot()
    types={x.attrib['name']:x for x in root.find('types')}
    fix=ns=='Fix'
    messages=[m for m in root.findall(SBE+'message') if selected is None or int(m.attrib['id']) in selected]
    def primitive(t):
        if t in SIZES: return t
        x=types[t]
        return x.get('primitiveType',x.get('encodingType'))
    def key(f): return f.get('id') if fix else f.get(MBX+'jsonPath',f.get('name'))
    def q(v): return json.dumps(v)
    def cpp(t): return 'uint8_t' if t=='char' else t+'_t'
    def decoder_fields(parent, indent='  '):
        lines=[]; offset=0
        for f in parent:
            if f.tag!='field': continue
            name=f.get('name'); t=f.get('type'); p=primitive(t); size=SIZES[p]
            if types.get(t) is not None and int(types[t].get('length','1'))!=1: raise ValueError(t)
            since=int(f.get('sinceVersion','0'))
            opt=f.get('presence')=='optional'; null='uint8_t(0)' if p=='char' else f'nullValue<{cpp(p)}>()'
            lines.append(f'{indent}auto v_{name} = {null};')
            lines.append(f'{indent}if (version >= {since}) {{ requireBlock(blockLength, {offset+size}); v_{name} = reader.at<{cpp(p)}>(start + {offset}); }}')
            if t=='boolEnum':
                lines.append(f'{indent}if (version >= {since} && v_{name} > 1' + (f' && v_{name} != {null}' if opt else '') + ') throw std::runtime_error("Invalid SBE boolean");')
            expr=f'std::to_string(v_{name})'
            if p=='char': expr=f'std::string(1, static_cast<char>(v_{name}))'
            if t=='mantissa64': expr=f'decimal(v_{name}, v_{f.get(MBX+"exponent")})'
            elif t=='boolEnum': expr=f'(v_{name} ? "Y" : "N")' if fix else f'(v_{name} != 0)'
            elif not fix and types.get(t) is not None and types[t].tag=='enum': expr=f'enum_{t}(v_{name})'
            cond=f'version >= {since}' + (f' && v_{name} != {null}' if opt else '')
            lines.append(f'{indent}if ({cond}) put(out, {q(key(f))}, {expr}, allocator);')
            if opt and not fix and MBX+'jsonDefaultValue' in f.attrib:
                lines.append(f'{indent}else put(out, {q(key(f))}, {q(f.get(MBX+"jsonDefaultValue"))}, allocator);')
            offset+=size
        lines.append(f'{indent}reader.position = start + blockLength;')
        for f in parent:
            if f.tag=='group':
                dim=types[f.get('dimensionType','groupSizeEncoding')]
                dims=[primitive(c.get('primitiveType',c.get('type'))) for c in dim]
                lines += [f'{indent}{{',f'{indent}  auto groupBlock = reader.read<{cpp(dims[0])}>();',f'{indent}  auto count = reader.read<{cpp(dims[1])}>();',f'{indent}  reader.checkCount(count, groupBlock);',f'{indent}  rj::Value group(rj::kArrayType);',f'{indent}  for (uint32_t i = 0; i < count; ++i) {{',f'{indent}    auto start = reader.position;',f'{indent}    size_t blockLength = groupBlock;',f'{indent}    reader.require(blockLength);',f'{indent}    rj::Value out(rj::kObjectType);']
                lines+=decoder_fields(f,indent+'    ')
                lines += [f'{indent}    group.PushBack(out, allocator);',f'{indent}  }}',f'{indent}  out.AddMember(rj::Value({q(key(f))}, allocator), group, allocator);',f'{indent}}}']
            elif f.tag=='data':
                composite=types[f.get('type')]; p=composite[0].get('primitiveType'); length=cpp(p)
                lines.append(f'{indent}{{ auto data = reader.string<{length}>();')
                if 'MessageData' in f.get('type') or 'messageData' in f.get('type'):
                    lines.append(f'{indent}  if (!data.empty()) {{ auto nested = decode(data, allocator, depth + 1); out.AddMember(rj::Value({q(key(f))}, allocator), nested, allocator); }}')
                else:
                    lines.append(f'{indent}  put(out, {q(key(f))}, data, allocator);')
                lines.append(f'{indent}}}')
        return lines
    out=['// Generated by tools/generate_binance_protocol_sbe.py; do not edit.', '#pragma once', '#include "ccapi_cpp/service/ccapi_binance_protocol_sbe.h"',f'namespace ccapi {{ namespace BinanceProtocolSbe {{ namespace {ns} {{',f'inline constexpr uint16_t schemaId = {root.get("id")};',f'inline constexpr uint16_t schemaVersion = {root.get("version")};','inline rj::Value decode(std::string_view bytes, Allocator& allocator, unsigned depth = 0);']
    if fix:
        out.append(f'inline constexpr uint16_t requestSchemaVersion = {FIX_REQUEST_VERSION};')
    if not fix:
        used={f.get('type') for m in messages for f in m.iter('field')}
        for t in sorted(used):
            x=types.get(t)
            if x is None or x.tag!='enum' or t=='boolEnum': continue
            out += [f'inline const char* enum_{t}(uint8_t value) {{', '  switch (value) {']
            seen=set()
            for v in x:
                if v.text in seen: continue
                seen.add(v.text)
                out.append(f'    case {v.text}: return {q(v.get(MBX+"jsonValue",v.get("name")))};')
            out+=['    default: throw std::runtime_error("Unknown SBE enum");','  }','}']
    for m in messages:
        out += [f'inline rj::Value decode{m.get("id")}(Reader& reader, size_t blockLength, uint16_t version, Allocator& allocator, unsigned depth) {{','  auto start = reader.position;', '  reader.require(blockLength);','  rj::Value out(rj::kObjectType);']
        out+=decoder_fields(m)
        out+=['  return out;','}']
    out+=['inline rj::Value decode(std::string_view bytes, Allocator& allocator, unsigned depth) {','  if (depth > 4 || bytes.size() > (1u << 20)) throw std::runtime_error("SBE message limit exceeded");','  Reader reader(bytes);']
    if fix:
        out+=['  if (reader.read<uint32_t>() != bytes.size() || reader.read<uint16_t>() != 0xeb50) throw std::runtime_error("Invalid FIX SBE SOFH");']
    out+=['  auto blockLength = reader.read<uint16_t>();','  auto templateId = reader.read<uint16_t>();','  if (reader.read<uint16_t>() != schemaId) throw std::runtime_error("Unexpected SBE schema ID");','  auto version = reader.read<uint16_t>();','  if (version > schemaVersion) throw std::runtime_error("Unsupported SBE schema version: received " + std::to_string(schemaId) + ":" + std::to_string(version) + ", supported through " + std::to_string(schemaId) + ":" + std::to_string(schemaVersion));']
    if fix: out+=['  auto sequence = reader.read<uint32_t>();','  auto sendingTime = reader.read<int64_t>();']
    out+=['  rj::Value out;', '  switch (templateId) {']
    for m in messages:
        out.append(f'    case {m.get("id")}: out = decode{m.get("id")}(reader, blockLength, version, allocator, depth); break;')
    out+=['    default: throw std::runtime_error("Unsupported SBE template: " + std::to_string(templateId));','  }','  if (reader.position != bytes.size()) throw std::runtime_error("Trailing SBE bytes");','  put(out, "_templateId", std::to_string(templateId), allocator);']
    if fix: out+=['  put(out, "34", std::to_string(sequence), allocator);','  put(out, "52", std::to_string(sendingTime), allocator);']
    out+=['  return out;','}']
    if fix:
        requests={20001,20002,20004,20008,99,101,103,105,120,200,202}
        for m in messages:
            tid=int(m.get('id'))
            if tid not in requests: continue
            fixed=[f for f in m if f.tag=='field' and int(f.get('sinceVersion','0')) <= FIX_REQUEST_VERSION]; block=sum(SIZES[primitive(f.get('type'))] for f in fixed)
            out += [f'inline std::string encode{tid}(const Params& params, uint32_t sequence, int64_t sendingTime) {{','  Writer writer;',f'  writer.header({block}, {tid}, schemaId, requestSchemaVersion, sequence, sendingTime);','  Parameters input(params);']
            for f in fixed:
                t=f.get('type'); p=primitive(t); name=f.get('name'); tag=f.get('id'); optional=f.get('presence')=='optional'
                call=f'input.number<{cpp(p)}>({tag}, {str(optional).lower()}, {str(p=="char").lower()}, {str(t=="boolEnum").lower()})'
                if t=='mantissa64':
                    exp=next(x for x in fixed if x.get('name')==f.get(MBX+'exponent')).get('id')
                    call=f'input.mantissa({tag}, {exp}, {str(optional).lower()})'
                out.append(f'  writer.write<{cpp(p)}>({call});')
            for f in m:
                if f.tag=='group':
                    # Only MarketDataRequest currently sends groups; one scalar per entry.
                    dim=types[f.get('dimensionType')]; child=list(f)[0]; tag=f.get('id'); ct=child.get('type')
                    out+=[f'  {{ auto entries = input.group({tag}, {child.get("id")});',f'    writer.write<{cpp(dim[0].get("primitiveType"))}>({0 if child.tag=="data" else SIZES[primitive(ct)]});',f'    writer.write<{cpp(dim[1].get("primitiveType"))}>(checkedSize<{cpp(dim[1].get("primitiveType"))}>(entries.size()));','    for (const auto& entry : entries) {']
                    if child.tag=='data': out.append('      writer.string<uint8_t>(entry);')
                    else: out.append('      writer.write<uint8_t>(character(entry));')
                    out+=['    }','  }']
                elif f.tag=='data':
                    opt=f.get('type').startswith('optional'); p=types[f.get('type')][0].get('primitiveType')
                    out.append(f'  writer.string<{cpp(p)}>(input.string({f.get("id")}, {str(opt).lower()}));')
            out+=['  input.finish();','  return writer.finish();','}']
        out+=['inline std::string encode(const Params& params, uint32_t sequence, int64_t sendingTime) {','  auto type = Parameters(params).string(35, false);']
        for m in messages:
            if int(m.get('id')) in requests: out.append(f'  if (type == {q(m.get("semanticType"))}) return encode{m.get("id")}(params, sequence, sendingTime);')
        out+=['  throw std::runtime_error("Unsupported FIX SBE request type: " + type);','}']
        out+=['inline const char* messageType(unsigned templateId) {','  switch (templateId) {']
        for m in messages: out.append(f'    case {m.get("id")}: return {q(m.get("semanticType"))};')
        out+=['    default: throw std::runtime_error("Unknown FIX SBE template");','  }','}']
    out+=['}}}']
    path=ROOT/'include/ccapi_cpp/service'/f'ccapi_binance_{ns.lower()}_sbe_generated.h'
    path.write_text('\n'.join(out)+'\n')

generate('spot-fixsbe-1_2.xml','Fix')
generate('spot_3_5.xml','Ws',{50,51,52,53,100,101,300,301,302,305,503,504,601,602,603,604,606,607,610})
